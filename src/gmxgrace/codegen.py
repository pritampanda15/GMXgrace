"""Generate reproducible CLI commands, Python scripts, and JSON recipes from any FigureSpec."""

from __future__ import annotations

import json
import shlex
from typing import Any

from gmxgrace.models import FigureSpec


def _quote(s: str) -> str:
    return shlex.quote(s)


def generate_cli_command(
    spec: FigureSpec,
    dataset_filenames: dict[str, str],
    output_name: str = "figure.pdf",
) -> str:
    """Generate the exact gmxgrace CLI command reproducing a FigureSpec."""
    # Single-panel common case produces a super-clean direct CLI one-liner
    if len(spec.panels) == 1 and spec.nrows == 1 and spec.ncols == 1:
        p = spec.panels[0]
        files = [dataset_filenames.get(did, f"{did}.xvg") for did in p.dataset_ids]
        if not files:
            return "gmxgrace serve"

        is_matrix = any(f.lower().endswith(".xpm") for f in files)
        parts: list[str] = ["gmxgrace", "matrix" if is_matrix else "plot"]
        parts.extend(_quote(f) for f in files)
        parts.extend(["--journal", spec.journal])
        if spec.column_width != "single":
            parts.extend(["--width", spec.column_width])
        if spec.palette != "okabe-ito":
            parts.extend(["--palette", spec.palette])
        if spec.font_size is not None:
            parts.extend(["--font-size", str(spec.font_size)])
        if spec.line_width is not None:
            parts.extend(["--line-width", str(spec.line_width)])
        if spec.dpi != 300:
            parts.extend(["--dpi", str(spec.dpi)])
        if spec.transparent:
            parts.append("--transparent")

        if p.title:
            parts.extend(["--title", _quote(p.title)])
        if p.x_label:
            parts.extend(["--xlabel", _quote(p.x_label)])
        if p.y_label:
            parts.extend(["--ylabel", _quote(p.y_label)])
        if p.x_unit != "original":
            parts.extend(["--x-unit", p.x_unit])
        if p.y_unit != "original":
            parts.extend(["--y-unit", p.y_unit])
        if p.x_min is not None or p.x_max is not None:
            lo = "" if p.x_min is None else str(p.x_min)
            hi = "" if p.x_max is None else str(p.x_max)
            parts.extend(["--xlim", f"{lo}:{hi}"])
        if p.y_min is not None or p.y_max is not None:
            lo = "" if p.y_min is None else str(p.y_min)
            hi = "" if p.y_max is None else str(p.y_max)
            parts.extend(["--ylim", f"{lo}:{hi}"])

        if is_matrix:
            if p.cmap != "RdYlBu_r":
                parts.extend(["--cmap", p.cmap])
            if p.show_contours:
                parts.extend(["--contours", str(p.contour_levels)])
            else:
                parts.append("--no-contours")
            if p.colorbar_label:
                parts.extend(["--cbar-label", _quote(p.colorbar_label)])
        else:
            if p.smoothing_method != "none":
                parts.extend(["--smooth", p.smoothing_method, "--window", str(p.smoothing_window)])
            if p.aggregate != "none":
                parts.extend(["--aggregate", p.aggregate])
                if p.aggregate_show_individual:
                    parts.append("--show-replicates")
            if p.marginal_hist:
                parts.append("--marginal")
            if p.grid:
                parts.append("--grid")
            if not p.show_legend:
                parts.append("--no-legend")
            if p.show_mean_line:
                parts.append("--mean-line")
            if p.equilibration_fraction > 0:
                parts.extend(["--eq", str(p.equilibration_fraction)])

        parts.extend(["-o", _quote(output_name)])
        return " ".join(parts)

    # Multi-panel or heavily customized figure: reproduce via recipe JSON
    return f"gmxgrace render figure_recipe.json -o {_quote(output_name)}"


def generate_recipe_dict(
    spec: FigureSpec,
    dataset_filenames: dict[str, str],
) -> dict[str, Any]:
    """Generate a portable JSON recipe linking dataset IDs to filenames + FigureSpec."""
    used_ids: set[str] = set()
    for p in spec.panels:
        used_ids.update(p.dataset_ids)
    files_map = {did: dataset_filenames.get(did, f"{did}.xvg") for did in sorted(used_ids)}
    return {
        "gmxgrace_recipe_version": "1.0",
        "files": files_map,
        "spec": spec.model_dump(mode="json"),
    }


def generate_python_script(
    spec: FigureSpec,
    dataset_filenames: dict[str, str],
    output_name: str = "figure.pdf",
) -> str:
    """Generate a standalone, clean, reproducible Python script using the gmxgrace API."""
    recipe = generate_recipe_dict(spec, dataset_filenames)
    files_json = json.dumps(recipe["files"], indent=4)
    spec_json = json.dumps(recipe["spec"], indent=4)
    # Convert JSON booleans/null to valid Python literals cleanly via repr or json.loads
    return f'''"""Reproducible publication figure script generated by gmxgrace."""

import json
from gmxgrace import FigureSpec, parse_file, save_figure

# 1. Load GROMACS input files
FILES = {files_json}
datasets = {{ds_id: parse_file(path) for ds_id, path in FILES.items()}}

# 2. Declarative publication figure specification
SPEC_JSON = r"""{spec_json}"""
spec = FigureSpec.model_validate(json.loads(SPEC_JSON))

# 3. Render & export publication-quality figure (PDF, SVG, EPS, PNG, or TIFF)
out_path = save_figure(spec, datasets, {output_name!r})
print(f"Saved publication figure -> {{out_path}}")
'''
